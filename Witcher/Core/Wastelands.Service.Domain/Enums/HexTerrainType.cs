namespace Wastelands.Service.Domain.Enums
{
	/// <summary>
	/// Тип террейна гекса карты боя — определяет, как гекс влияет на передвижение (см.
	/// <see cref="Entities.BattleMapHex.MovementCost"/>). Как гекс выглядит, задаёт отдельно
	/// <see cref="HexTerrainStyle"/>: один и тот же тип может быть травой, песком, металлом и т.д.
	/// </summary>
	public enum HexTerrainType
	{
		/// <summary>Простой террейн — не мешает движению.</summary>
		Open = 0,

		/// <summary>Сложный террейн — движение через гекс стоит дороже (кустарник, мелководье, завалы).</summary>
		Difficult = 1,

		/// <summary>Непроходимый террейн — движение запрещено, но гекс видно насквозь (пропасть, глубокая вода).</summary>
		Impassable = 2,

		/// <summary>Стена — движение запрещено; в будущем будет блокировать и обзор.</summary>
		Wall = 3,

		/// <summary>Черное пространство — "ничего" за пределами игровой зоны (например, толща породы за стенами пещеры).</summary>
		Void = 4,
	}
}
